export function browserLocationErrorMessage(code: number): string {
  switch (code) {
    case 1:
      return "رفض المتصفح إذن الموقع. افتح إعدادات الموقع لهذا الموقع واسمح بالوصول، ثم أعد المحاولة.";
    case 2:
      return "تعذر تحديد الموقع. فعّل خدمات الموقع في الجهاز وتأكد من توفر إشارة.";
    case 3:
      return "انتهت مهلة تحديد الموقع. تأكد من تشغيل خدمات الموقع ثم أعد المحاولة.";
    default:
      return "تعذر تحديد موقعك. تحقق من إذن الموقع وإعدادات الجهاز ثم أعد المحاولة.";
  }
}
